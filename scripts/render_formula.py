"""Writes Formula/trackified.rb for a trackified-cli release from its checksums.txt."""
import sys

version, checksums_path = sys.argv[1], sys.argv[2]
sums = {}
for line in open(checksums_path):
    digest, name = line.split()
    sums[name] = digest
base = f"https://github.com/trackified/trackified-cli/releases/download/v{version}"

def asset(os_name: str, arch: str) -> str:
    name = f"trackified_{version}_{os_name}_{arch}.tar.gz"
    return f'      url "{base}/{name}"\n      sha256 "{sums[name]}"'

print(f'''# Generated by .github/workflows/update-formula.yml from trackified-cli v{version}. Do not edit.
class Trackified < Formula
  desc "Command-line client for the Trackified parcel-tracking API"
  homepage "https://trackified.net"
  version "{version}"
  license "MIT"

  on_macos do
    on_arm do
{asset("darwin", "arm64")}
    end
    on_intel do
{asset("darwin", "amd64")}
    end
  end

  on_linux do
    on_arm do
{asset("linux", "arm64")}
    end
    on_intel do
{asset("linux", "amd64")}
    end
  end

  def install
    bin.install "trackified"
  end

  test do
    assert_match version.to_s, shell_output("#{{bin}}/trackified version")
  end
end''')
